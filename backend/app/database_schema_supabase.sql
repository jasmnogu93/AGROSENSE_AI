-- =============================================================================
-- ESQUEMA RELACIONAL EN SUPABASE (POSTGRESQL) — RF6 (AGROSENSE AI)
-- Definimos claves primarias (PRIMARY KEY) y relaciones con ON DELETE CASCADE
-- para mantener la integridad entre módulos, lecturas, alertas y calendarios.
-- =============================================================================

-- 1. Tabla de Módulos Físicos / Invernaderos (Contextos SOA)
CREATE TABLE IF NOT EXISTS public.modulos_hidroponicos (
    id VARCHAR(50) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    ubicacion_fisica VARCHAR(100) DEFAULT 'Santo Tomás Temuco - Lab IoT',
    broker_topic_telemetria VARCHAR(100) NOT NULL,
    broker_topic_comandos VARCHAR(100) NOT NULL,
    creado_en TIMESTAMPTZ DEFAULT NOW(),
    activo BOOLEAN DEFAULT TRUE
);

-- 2. Tabla de Perfiles de Especies Cultivadas
CREATE TABLE IF NOT EXISTS public.perfiles_cultivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    especie VARCHAR(100) NOT NULL UNIQUE,
    temp_min DOUBLE PRECISION NOT NULL DEFAULT 18.0,
    temp_max DOUBLE PRECISION NOT NULL DEFAULT 24.0,
    humedad_min DOUBLE PRECISION NOT NULL DEFAULT 55.0,
    humedad_max DOUBLE PRECISION NOT NULL DEFAULT 75.0,
    dpv_min_kpa DOUBLE PRECISION NOT NULL DEFAULT 0.8,
    dpv_max_kpa DOUBLE PRECISION NOT NULL DEFAULT 1.2,
    recirculacion_minutos INTEGER DEFAULT 15,
    intervalo_riego_horas INTEGER DEFAULT 2
);

-- 3. Tabla de Asociación Módulo - Cultivo
CREATE TABLE IF NOT EXISTS public.asignacion_cultivo_modulo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id VARCHAR(50) NOT NULL REFERENCES public.modulos_hidroponicos(id) ON DELETE CASCADE,
    perfil_id BIGINT NOT NULL REFERENCES public.perfiles_cultivo(id) ON DELETE CASCADE,
    fecha_siembra DATE DEFAULT CURRENT_DATE,
    estado_cultivo VARCHAR(50) DEFAULT 'FLORACION'
);

-- 4. Tabla de Telemetría Histórica: en esta tabla guardamos las lecturas ambientales (RF5 y RF6)
CREATE TABLE IF NOT EXISTS public.telemetria_historica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id VARCHAR(50) NOT NULL REFERENCES public.modulos_hidroponicos(id) ON DELETE CASCADE,
    fecha_hora TIMESTAMPTZ DEFAULT NOW(),
    temp_ambiente DOUBLE PRECISION NOT NULL,
    humedad_ambiente DOUBLE PRECISION NOT NULL,
    presion_atmosferica DOUBLE PRECISION NOT NULL DEFAULT 1013.25,
    dpv_kpa DOUBLE PRECISION,
    nivel_estanque DOUBLE PRECISION NOT NULL DEFAULT 85.0,
    bomba_encendida BOOLEAN DEFAULT FALSE,
    servo_angulo INTEGER DEFAULT 0,
    pasos_motor_acumulados INTEGER DEFAULT 0,
    ph_solucion DOUBLE PRECISION,
    conductividad_ec DOUBLE PRECISION,
    luz_lux DOUBLE PRECISION,
    origen_dato VARCHAR(30) DEFAULT 'WIFI_ESP32'
);

-- Creamos este índice para acelerar las consultas históricas recientes de cada módulo
CREATE INDEX IF NOT EXISTS idx_telemetria_modulo_fecha
    ON public.telemetria_historica (modulo_id, id DESC);

-- 5. Tabla de Auditoría de Comandos (Riego manual, demo y cambios de calendario)
CREATE TABLE IF NOT EXISTS public.registro_comandos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id VARCHAR(50) NOT NULL REFERENCES public.modulos_hidroponicos(id) ON DELETE CASCADE,
    actuador VARCHAR(50) NOT NULL,
    accion VARCHAR(50) NOT NULL,
    parametro_valor DOUBLE PRECISION DEFAULT 0.0,
    disparado_por VARCHAR(50) NOT NULL,
    fecha_hora TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Tabla de Alertas y Notificaciones: aquí registramos los avisos de riego y clima (RF2 y RF4)
CREATE TABLE IF NOT EXISTS public.alertas_sistema (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id VARCHAR(50) NOT NULL REFERENCES public.modulos_hidroponicos(id) ON DELETE CASCADE,
    severidad VARCHAR(20) NOT NULL,
    mensaje TEXT NOT NULL,
    leida BOOLEAN DEFAULT FALSE,
    fecha_hora TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Tabla de Calendario Semanal: guarda los días activos, hora y frecuencia de registro (RF1 y RF5)
CREATE TABLE IF NOT EXISTS public.calendario_semanal (
    modulo_id VARCHAR(50) PRIMARY KEY REFERENCES public.modulos_hidroponicos(id) ON DELETE CASCADE,
    dias_activos_json TEXT NOT NULL,
    hora_riego VARCHAR(10) NOT NULL DEFAULT '08:30',
    duracion_minutos INTEGER NOT NULL DEFAULT 20,
    intervalo_horas INTEGER NOT NULL DEFAULT 24,
    frecuencia_registro_min INTEGER NOT NULL DEFAULT 60,
    actualizado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Tabla de Estado Operativo Actual por Módulo (Última lectura en tiempo real)
CREATE TABLE IF NOT EXISTS public.estado_modulo (
    modulo_id VARCHAR(50) PRIMARY KEY REFERENCES public.modulos_hidroponicos(id) ON DELETE CASCADE,
    temp_ambiente DOUBLE PRECISION NOT NULL,
    humedad_ambiente DOUBLE PRECISION NOT NULL,
    presion_hpa DOUBLE PRECISION NOT NULL DEFAULT 1013.25,
    nivel_estanque DOUBLE PRECISION NOT NULL DEFAULT 85.0,
    dpv_kpa DOUBLE PRECISION,
    bomba_encendida BOOLEAN DEFAULT FALSE,
    servo_angulo INTEGER DEFAULT 0,
    pasos_motor_acumulados INTEGER DEFAULT 0,
    humedad_sustrato DOUBLE PRECISION,
    ext_temp_ambiente DOUBLE PRECISION,
    ext_humedad_ambiente DOUBLE PRECISION,
    actualizado_en TIMESTAMPTZ DEFAULT NOW()
);

-- Deshabilitar RLS en estas tablas para acceso directo desde el prototipo backend FastAPI
ALTER TABLE public.modulos_hidroponicos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.perfiles_cultivo DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.asignacion_cultivo_modulo DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.telemetria_historica DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.registro_comandos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.alertas_sistema DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.calendario_semanal DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.estado_modulo DISABLE ROW LEVEL SECURITY;

